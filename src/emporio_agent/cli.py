"""Command line front end: interactive chat, session resume and a scripted runner.

    python -m emporio_agent                        # chat
    python -m emporio_agent --resume <session-id>  # continue a saved conversation
    python -m emporio_agent --script scenario.txt --out examples/01.md   # replay customer messages

The agent core (agent.py) does no I/O, so this module is the only place that prints or reads input.
"""
import argparse
import logging
import os
import sys
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Callable

from emporio_agent.agent import Agent, TurnResult
from emporio_agent.config import REPO_ROOT, store_now
from emporio_agent.data.store import Store
from emporio_agent.llm import LLMClient, LLMNotConfigured
from emporio_agent.policies.retriever import PolicyRetriever
from emporio_agent.session import Session

SESSIONS_DIR = REPO_ROOT / ".conversations"

BANNER = (
    "Empório da Música — virtual assistant (prototype)\n"
    "Type your message as a customer would. Commands: /new  /tools  /exit\n"
)


@dataclass
class Turn:
    user: str
    result: TurnResult


def build_agent() -> Agent:
    llm = LLMClient.from_env()
    retriever = PolicyRetriever(embedder=llm, model_name=llm.embedding_model)
    return Agent(llm, Store(), retriever)


def _tool_line(call) -> str:
    return f"{call.name}({call.arguments})"


def chat_loop(agent: Agent, session: Session, sessions_dir: Path, read: Callable[[str], str] = input,
              write: Callable[[str], None] = print, show_tools: bool = False) -> Session:
    write(BANNER)
    if session.messages:
        write(f"Resuming session {session.id} ({len(session.messages)} messages).\n")
    while True:
        try:
            text = read("You: ").strip()
        except (EOFError, KeyboardInterrupt):
            write("")
            break
        if not text:
            continue
        if text in ("/exit", "/quit"):
            break
        if text == "/tools":
            show_tools = not show_tools
            write(f"(tool calls {'shown' if show_tools else 'hidden'})")
            continue
        if text == "/new":
            session = Session()
            write(f"(new session {session.id})")
            continue

        result = agent.reply(session, text)
        if show_tools:
            for call in result.tool_calls:
                write(f"  [tool] {_tool_line(call)}")
        write(f"Assistant: {result.text}\n")
        if not result.failed:
            session.save(sessions_dir)  # saved after every turn, so a crash loses nothing

    if session.messages:
        write(f"Session saved. Resume with: python -m emporio_agent --resume {session.id}")
    return session


def read_script(path: Path) -> tuple[str, list[str]]:
    """One customer message per line. A first '# title' line names the scenario; other '#' lines and
    blank lines are ignored."""
    title, messages = path.stem, []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("#"):
            if not messages and line.startswith("# ") and title == path.stem:
                title = line[2:].strip()
            continue
        messages.append(line)
    return title, messages


def run_script(agent: Agent, session: Session, messages: list[str]) -> list[Turn]:
    return [Turn(text, agent.reply(session, text)) for text in messages]


def to_markdown(title: str, turns: list[Turn], store_time: datetime, model: str | None = None) -> str:
    lines = [f"# {title}", ""]
    meta = f"Store clock: {store_time:%d/%m/%Y %H:%M} (America/Campo_Grande)"
    if model:
        meta += f" · Model: `{model}`"
    lines += [f"_{meta}. Generated by running the real agent, not edited by hand._", ""]
    for turn in turns:
        lines += [f"**Customer:** {turn.user}", ""]
        for call in turn.result.tool_calls:
            lines.append(f"> 🔧 `{_tool_line(call)}`")
        if turn.result.tool_calls:
            lines.append("")
        lines += [f"**Assistant:** {turn.result.text}", ""]
    return "\n".join(lines).rstrip() + "\n"


def parse_args(argv: list[str] | None) -> argparse.Namespace:
    p = argparse.ArgumentParser(prog="emporio_agent", description="Empório da Música customer service agent")
    p.add_argument("--resume", metavar="SESSION_ID", help="continue a saved conversation")
    p.add_argument("--now", metavar="ISO", help="fixed store clock, e.g. 2026-02-20T10:00 (default: real time)")
    p.add_argument("--tools", action="store_true", help="show tool calls in the chat")
    p.add_argument("--script", type=Path, metavar="FILE", help="replay customer messages from a text file")
    p.add_argument("--out", type=Path, metavar="FILE.md", help="with --script: write the transcript here")
    p.add_argument("--sessions-dir", type=Path, default=SESSIONS_DIR, help=argparse.SUPPRESS)
    p.add_argument("--verbose", action="store_true", help="log what the agent does")
    return p.parse_args(argv)


def main(argv: list[str] | None = None, agent_factory: Callable[[], Agent] = build_agent,
         read: Callable[[str], str] = input, write: Callable[[str], None] = print) -> int:
    args = parse_args(argv)
    # The Windows console defaults to a legacy code page that garbles Portuguese accents.
    for stream in (sys.stdout, sys.stdin):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    logging.basicConfig(level=logging.INFO if args.verbose else logging.WARNING, format="[%(name)s] %(message)s")
    logging.getLogger("httpx").setLevel(logging.WARNING)

    if args.now:
        try:
            datetime.fromisoformat(args.now)
        except ValueError:
            write(f"Invalid --now value '{args.now}'. Use ISO format, e.g. 2026-02-20T10:00")
            return 2
        os.environ["STORE_NOW"] = args.now

    try:
        agent = agent_factory()
    except LLMNotConfigured as exc:
        write(f"Configuration error: {exc}")
        return 2

    if args.resume:
        try:
            session = Session.load(args.sessions_dir, args.resume)
        except FileNotFoundError:
            write(f"No saved session '{args.resume}' in {args.sessions_dir}")
            return 2
    else:
        session = Session()

    if args.script:
        title, messages = read_script(args.script)
        turns = run_script(agent, session, messages)
        text = to_markdown(title, turns, store_now(), getattr(agent.llm, "model", None))
        if args.out:
            args.out.parent.mkdir(parents=True, exist_ok=True)
            args.out.write_text(text, encoding="utf-8")
            write(f"Transcript written to {args.out}")
        else:
            write(text)
        failed = [t.user for t in turns if t.result.failed]
        return 1 if failed else 0

    chat_loop(agent, session, args.sessions_dir, read, write, show_tools=args.tools)
    return 0
